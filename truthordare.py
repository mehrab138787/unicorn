    """Restart from a stopped or finished state."""
    g["state"] = "playing"
    g["started_at"] = now_iso()
    order = list(g["players"].keys()); random.shuffle(order)
    g["order"] = order; g["current_index"] = 0
    for uid in g["order"]:
        g["players"][uid]["turns_done"] = 0
