async def _stop_task_safe(task, settle=0.35):
    if task and not task.done():
        try: task.cancel()
        except Exception: pass
        try: await asyncio.wait([task], timeout=2.0)
        except Exception: pass
    if settle > 0: await asyncio.sleep(settle)


