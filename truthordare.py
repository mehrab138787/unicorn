def time_bar_colored(remaining, total, width=18):
    if total <= 0: return "⬜" * width
    pct = max(0, min(100, int(100 * remaining / total)))
    f = int(pct / 100 * width); e = width - f
    if pct > 60: return "🟩" * f + "⬜" * e
    if pct > 30: return "🟨" * f + "⬜" * e
    return "🟥" * f + "⬜" * e


